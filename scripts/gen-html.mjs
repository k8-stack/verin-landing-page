#!/usr/bin/env node
/*
 * Generates the multi-page HTML entry files from one template so every page
 * shares the same head (fonts, favicon, social tags). Run after editing PAGES:
 *   node scripts/gen-html.mjs
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;

const PAGES = [
  { file: 'index.html', entry: '/src/main.tsx', title: 'Verin — Crypto market intelligence & onchain data',
    description: 'Explore crypto markets and build with onchain data: token discovery, prices, price history and pool-level liquidity across networks.' },
  { file: 'solutions/index.html', entry: '/src/entries/solutions.tsx', title: 'Solutions — Verin',
    description: 'How Verin’s market data fits wallets, trading platforms, analytics products, DeFi protocols and developers.' },
  { file: 'developers/index.html', entry: '/src/entries/developers.tsx', title: 'Developers — Verin',
    description: 'Data API status, how the Verin preview computes its data, its data model, and how to request early API access.' },
  { file: 'security/index.html', entry: '/src/entries/security.tsx', title: 'Security & data — Verin',
    description: 'A plain account of how the current Verin build handles data, third parties and availability.' },
  { file: 'contact/index.html', entry: '/src/entries/contact.tsx', title: 'Contact — Verin',
    description: 'Talk to the Verin team about market-data integrations, API access, partnerships or commercial terms.' },
  { file: 'privacy/index.html', entry: '/src/entries/privacy.tsx', title: 'Privacy notice — Verin',
    description: 'How the Verin website handles personal information.' },
  { file: '404.html', entry: '/src/entries/notfound.tsx', title: 'Page not found — Verin', robots: 'noindex',
    description: 'This page could not be found.' },
];

const esc = (s) => s.replace(/&/g, '&amp;').replace(/"/g, '&quot;').replace(/</g, '&lt;');

for (const p of PAGES) {
  const html = `<!doctype html>
<!-- Generated by scripts/gen-html.mjs — edit there, not here. -->
<html lang="en">
  <head>
    <meta charset="UTF-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1.0" />
    <meta name="color-scheme" content="light" />
    <meta name="theme-color" content="#ffffff" />
    <title>${esc(p.title)}</title>
    <meta name="description" content="${esc(p.description)}" />${p.robots ? `\n    <meta name="robots" content="${p.robots}" />` : ''}
    <meta property="og:type" content="website" />
    <meta property="og:site_name" content="Verin" />
    <meta property="og:title" content="${esc(p.title)}" />
    <meta property="og:description" content="${esc(p.description)}" />
    <meta property="og:image" content="%VITE_SITE_URL%/og-image.png" />
    <meta property="og:image:width" content="1200" />
    <meta property="og:image:height" content="630" />
    <meta name="twitter:card" content="summary_large_image" />
    <link rel="icon" href="/favicon.svg" type="image/svg+xml" />
    <link rel="preconnect" href="https://fonts.googleapis.com" />
    <link rel="preconnect" href="https://fonts.gstatic.com" crossorigin />
    <link
      href="https://fonts.googleapis.com/css2?family=Doto:wght@700;900&family=Inter+Tight:wght@400;500;600;700&family=Roboto+Mono:wght@400;500&display=swap"
      rel="stylesheet"
    />
  </head>
  <body>
    <div id="root"></div>
    <script type="module" src="${p.entry}"></script>
  </body>
</html>
`;
  const out = join(ROOT, p.file);
  mkdirSync(dirname(out), { recursive: true });
  writeFileSync(out, html);
}
console.log(`Wrote ${PAGES.length} HTML entries.`);
export { PAGES };
